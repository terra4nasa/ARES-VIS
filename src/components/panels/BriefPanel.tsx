"use client";
import { Printer, FileDown, FileJson } from "lucide-react";
import { useStore } from "@/lib/store";
import { useEvaPlan, useSpaceWeather } from "@/lib/hooks";
import { PanelFrame } from "./PanelFrame";
import { SITE, POIS } from "@/lib/data";
import { fmtLst } from "@/lib/eva";
import { toast } from "sonner";

function download(name: string, content: string, mime: string) {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = name;
  a.click();
  URL.revokeObjectURL(url);
}

export function BriefPanel() {
  const route = useStore((s) => s.route);
  const eva = useStore((s) => s.eva);
  const { plan, profile, sw } = useEvaPlan();

  const gpx = () => {
    if (route.length < 2) {
      toast.error("Route needs at least 2 waypoints");
      return;
    }
    const pts = route
      .map(
        (w) =>
          `  <wpt lat="${w.lat.toFixed(6)}" lon="${w.lon.toFixed(6)}"><name>${w.name}</name><ele>${w.elevM ?? 0}</ele></wpt>`
      )
      .join("\n");
    const trk = profile.map((p) => `<trkpt lat="${p.lat.toFixed(6)}" lon="${p.lon.toFixed(6)}"><ele>${p.elev.toFixed(0)}</ele></trkpt>`).join("");
    const doc = `<?xml version="1.0" encoding="UTF-8"?>
<gpx version="1.1" creator="ARES-VIS" xmlns="http://www.topografix.com/GPX/1/1">
  <metadata><name>Marswalk-01 Elysium Planitia</name><desc>Generated by ARES-VIS — coordinates in Mars planetocentric degrees (Mars-2000 sphere)</desc></metadata>
${pts}
  <trk><name>ARES-VIS track (200 m samples, HRSC-MOLA elevations)</name><trkseg>${trk}</trkseg></trk>
</gpx>`;
    download("aresvis-marswalk01.gpx", doc, "application/gpx+xml");
    toast.success("GPX downloaded");
  };

  const json = () => {
    const payload = {
      mission: "MARSWALK-01",
      site: SITE,
      evaParams: eva,
      route,
      legs: plan.legs,
      totals: { distM: plan.totalDistM, timeH: plan.totalTimeH, o2Pct: plan.o2UsedPct, doseMsv: plan.doseMsv },
      spaceWeather: sw,
      terrainNote: "Elevations in meters relative to MOLA areoid; sampled from USGS HRSC-MOLA blended DEM v2 (200 m/px).",
      generated: new Date().toISOString(),
    };
    download("aresvis-mission-plan.json", JSON.stringify(payload, null, 2), "application/json");
    toast.success("Mission plan JSON downloaded");
  };

  const addedPois = route.map((w) => POIS.find((p) => p.id === w.poiId)).filter(Boolean);

  return (
    <PanelFrame id="brief" title="MISSION BRIEF" subtitle="print · export · hand-off">
      <div className="space-y-4 text-[11px]">
        <div className="rounded-sm border border-[var(--hud-border-dim)] bg-[rgba(10,15,22,0.6)] p-3">
          <h3 className="font-display text-sm tracking-[0.18em] text-[var(--hud-amber)]">MARSWALK-01 · ELYSIUM PLANITIA</h3>
          <div className="hud-label mt-1">{SITE.name} · {SITE.lat.toFixed(4)}°N {SITE.lon.toFixed(4)}°E · elev {SITE.elevM} m</div>
          <dl className="mt-3 grid grid-cols-2 gap-x-3 gap-y-1.5">
            <div><dt className="hud-label">crew</dt><dd>{eva.crew} astronauts</dd></div>
            <div><dt className="hud-label">suit endurance</dt><dd>{eva.suitHours} h</dd></div>
            <div><dt className="hud-label">walk speed</dt><dd>{eva.speedKmh.toFixed(1)} km/h</dd></div>
            <div><dt className="hud-label">eva window</dt><dd>{fmtLst(eva.startLst)} → {route.length > 1 ? fmtLst(plan.lstEnd) : "—"} LST</dd></div>
            <div><dt className="hud-label">distance</dt><dd>{(plan.totalDistM / 1000).toFixed(2)} km</dd></div>
            <div><dt className="hud-label">duration</dt><dd>{plan.totalTimeH.toFixed(2)} h</dd></div>
            <div><dt className="hud-label">o₂ budget</dt><dd className={plan.o2UsedPct > 65 ? "text-[var(--hud-red)]" : ""}>{plan.o2UsedPct.toFixed(0)}%</dd></div>
            <div><dt className="hud-label">radiation dose</dt><dd>{plan.doseMsv > 0 ? `${plan.doseMsv.toFixed(3)} mSv` : "—"}</dd></div>
            <div><dt className="hud-label">space wx state</dt><dd>{sw?.marsSurface.evaState.replace("_", " ") ?? "…"}</dd></div>
            <div><dt className="hud-label">dust opacity</dt><dd>τ ≈ 0.45</dd></div>
          </dl>
          {plan.warnings.length > 0 && (
            <ul className="mt-3 space-y-1 border-t border-[var(--hud-border-dim)] pt-2 text-[var(--hud-red)]">
              {plan.warnings.map((w, i) => <li key={i}>▲ {w}</li>)}
            </ul>
          )}
        </div>

        <div className="rounded-sm border border-[var(--hud-border-dim)] p-3">
          <h3 className="hud-label mb-2 text-[var(--hud-orange)]">route of march</h3>
          <ol className="space-y-1">
            {route.map((w, i) => {
              const poi = addedPois[i - 1] as (typeof POIS)[number] | undefined;
              return (
                <li key={w.id} className="flex items-start gap-2 border-b border-[rgba(255,255,255,0.05)] pb-1">
                  <span className={`font-display w-5 ${i === 0 ? "text-[var(--hud-green)]" : "text-[var(--hud-amber)]"}`}>{i === 0 ? "⌂" : i}</span>
                  <div>
                    <b>{w.name}</b>
                    <span className="text-[var(--hud-dim)]"> · {w.lat.toFixed(4)}°N {w.lon.toFixed(4)}°E</span>
                    {w.elevM !== undefined && <span className="text-[var(--hud-cyan)]"> · {w.elevM} m</span>}
                    {poi && <div className="text-[10px] text-[var(--hud-dim)]">{poi.activity}</div>}
                  </div>
                </li>
              );
            })}
            {route.length === 0 && <li className="text-[var(--hud-dim)]">No route yet.</li>}
          </ol>
        </div>

        <div className="rounded-sm border border-[var(--hud-border-dim)] p-3 text-[10px] leading-relaxed text-[var(--hud-dim)]">
          <h3 className="hud-label mb-2 text-[var(--hud-orange)]">data provenance</h3>
          Basemap: MRO CTX mosaic (USGS/Esri OnMars). Topography: HRSC-MOLA blended DEM v2 (200 m/px, USGS/PDS) — relief,
          slope-hazard and route profiles derived. Thermal: THEMIS Day/Night IR controlled mosaics (Odyssey, 100 m/px,
          USGS/PDS). Weather: InSight APSS/TWINS climatology (illustrative). Radiation: Curiosity RAD calibration × live
          NOAA SWPC (F10.7, GOES protons, Kp). Seismicity: InSight Marsquake Service catalog. POV: NASA Image Library.
        </div>

        <div className="flex flex-wrap gap-2">
          <button className="hud-btn active" onClick={() => window.print()}>
            <Printer className="h-4 w-4" /> print / save pdf
          </button>
          <button className="hud-btn" onClick={gpx}>
            <FileDown className="h-4 w-4" /> gpx
          </button>
          <button className="hud-btn" onClick={json}>
            <FileJson className="h-4 w-4" /> json
          </button>
        </div>
        <p className="text-[10px] leading-snug text-[var(--hud-dim)]">
          Print exports the panel as a printable mission hand-out. GPX/JSON feed the plan into rover-support systems or
          the crew&apos;s field tablets.
        </p>
      </div>
    </PanelFrame>
  );
}
